#!/usr/bin/env python3
"""Evidence tables for the PW-1 draft sweep.
usage: make_tables.py SNAPDIR STAGEDIR OUTDIR
Writes OUTDIR/REPLACEMENTS.md (every rule, hit count per draft; every metaphor / judge / budget /
config / pre-registration / ledger / gate / special replacement with its sentence) and
OUTDIR/RESIDUALS.md (token scan of the rendered source, comments and \\label/\\ref keys excluded,
before and after, per draft, with every residual line printed)."""
import json, sys, subprocess, os
SNAP, STAGE, OUT = sys.argv[1:4]
D = ['DRAFT-v2', 'DRAFT-v2-style']
here = os.path.dirname(os.path.abspath(__file__))
c = {d: json.load(open(os.path.join(STAGE, d + '.counts.json'))) for d in D}

L = ['# REPLACEMENTS — pw1-draft-sweeps', '',
     'Generated by `pw1_draft_sweeps/make_tables.py` from the `*.counts.json` that `sweep.py` writes. '
     'Rule order is execution order. A rule written for one draft\'s wording shows 0 in the other; '
     'the residual scan (RESIDUALS.md) is the proof that nothing was missed.', '',
     '## 1. Every rule, hits per draft', '', '| # | rule | class | DRAFT-v2 | DRAFT-v2-style | equal |', '|---|---|---|---|---|---|']
cls = {}
for e in c['DRAFT-v2']['log'] + c['DRAFT-v2-style']['log']:
    cls[e['rule']] = e['class']
tot = {d: {} for d in D}
for i, k in enumerate(c['DRAFT-v2']['counts'], 1):
    a, b = c['DRAFT-v2']['counts'][k], c['DRAFT-v2-style']['counts'].get(k, 0)
    kc = cls.get(k, {'riv': 'rival', 'st-': 'store', 'cor': 'corner', 'xr-': 'xref', 'not': 'note'}.get(k[:3], ''))
    L.append('| %d | `%s` | %s | %d | %d | %s |' % (i, k, kc, a, b, 'yes' if a == b else '**no**'))
    for d, v in ((D[0], a), (D[1], b)):
        tot[d][kc] = tot[d].get(kc, 0) + v
L += ['', '## 2. Totals per class', '', '| class | DRAFT-v2 | DRAFT-v2-style |', '|---|---|---|']
for k in sorted(set(tot[D[0]]) | set(tot[D[1]])):
    L.append('| %s | %d | %d |' % (k or '(generic)', tot[D[0]].get(k, 0), tot[D[1]].get(k, 0)))
L += ['', '## 3. Every in-context replacement (economic metaphors one by one, then judge, budget, configuration names, pre-registration/scored-run, ledger, gate/charter, special), with the sentence it sat in', '']
for d in D:
    L += ['### %s' % d, '']
    for j, e in enumerate(c[d]['log'], 1):
        L.append('%d. **[%s / `%s`]** `%s` → `%s`  ' % (j, e['class'], e['rule'], e['before'], e['after']))
        L.append('   sentence before: %s' % e['sentence_before'].replace('|', '\\|'))
    L.append('')
open(os.path.join(OUT, 'REPLACEMENTS.md'), 'w').write('\n'.join(L) + '\n')

R = ['# RESIDUALS — rendered-source token scan, before and after', '',
     'Command (per draft): `python3 pw1_draft_sweeps/scan.py <DRAFT>.tex --lines` '
     '(word-boundary regexes; LaTeX comments and `\\label`/`\\ref`/`\\cite` keys excluded; case-insensitive except A1, A10, bare CLU, `\\S`).', '',
     '| token | v2 before | v2 after | style before | style after |', '|---|---|---|---|---|']
def scan(p, lines=False):
    out = subprocess.run([sys.executable, os.path.join(here, 'scan.py'), p] + (['--lines'] if lines else []), capture_output=True, text=True).stdout
    return out
res = {}
for d in D:
    for tag, p in (('b', os.path.join(SNAP, d + '.tex')), ('a', os.path.join(STAGE, d + '.tex'))):
        for line in scan(p).splitlines():
            k, n = line[:22].strip(), int(line[22:].strip())
            res.setdefault(k, {})[(d, tag)] = n
for k, v in res.items():
    R.append('| %s | %d | %d | %d | %d |' % (k.replace('|', '\\|'), v[(D[0], 'b')], v[(D[0], 'a')], v[(D[1], 'b')], v[(D[1], 'a')]))
R += ['', '## Every residual line after the sweep', '']
for d in D:
    R += ['### %s' % d, '', '```', scan(os.path.join(STAGE, d + '.tex'), True).rstrip(), '```', '']
open(os.path.join(OUT, 'RESIDUALS.md'), 'w').write('\n'.join(R) + '\n')
print('ok')
