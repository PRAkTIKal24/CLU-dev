"""w19 tables: every cell generated from the JSONs.  python scripts/w19_tables.py <out_dir>

⛔ Every table names its condition; no w16 row appears in any table; CMAZE-T only.
Seed count is a column.  Byte figures name their convention.
"""
import json
import os
import sys
import numpy as np
CONDS = ("WORDS-MAIN", "WORDS-FULL", "OBS", "BOTH")
DIAGS = ("OBS-X10",)
def f(x):
    return "—" if x is None else "%.3f" % x


def seeds_json(out, cond, leg):
    d = os.path.join(out, leg)
    ps = [os.path.join(d, "%s_%s_seed%d.json" % (cond, leg, s)) for s in (0, 1, 2)]
    if not all(os.path.exists(p) for p in ps):
        return None
    return [json.load(open(p)) for p in ps]


def bars(out, cond, leg):
    p = os.path.join(out, leg, "BARS-%s-%s.json" % (cond, leg))
    return json.load(open(p)) if os.path.exists(p) else None


def arm_table(runs, row, cond, leg):
    L = ["", "#### CMAZE-T · condition **%s** · %s · row `%s` (exact) · n_seeds = %d · rows/seed %s"
         % (cond, leg.upper(), row, len(runs), [r["ROWS"][row]["n"] for r in runs]), "",
         "| arm | mean | seed 0 | seed 1 | seed 2 |", "|---|---|---|---|---|"]
    keys = [k for k in runs[0]["ROWS"][row]
            if isinstance(runs[0]["ROWS"][row][k], (int, float)) and k != "n"
            and not k.endswith(":coverage")]
    order = (["CLU"] + [k for k in keys if k.startswith("rival: ")]
             + [k for k in keys if k.startswith("rival@10x-steps: ")]
             + [k for k in keys if k.startswith("diagnostic@")]
             + [k for k in keys if k.startswith("control: ")]
             + [k for k in keys if k.startswith("arm: ")]
             + [k for k in keys if k.startswith("floor: ")]
             + [k for k in keys if k.startswith("column: ")])
    for k in order:
        v = [r["ROWS"][row][k] for r in runs]
        name = k
        if k == "CLU" and cond == "WORDS-MAIN":
            name = "CLU (main effects only == the learned BLIND-SEQUENTIAL reading)"
        if k.startswith("rival: "):
            name = k.replace("rival: ", "rival (matched, 8,000 steps): ")
        if k.startswith("rival@10x-steps: "):
            name = k.replace("rival@10x-steps: ", "rival (matched, 80,000 steps = 10x): ")
        if k.startswith("diagnostic@"):
            name = k + " (8,000 steps; NOT matched, never a bar)"
        if k.startswith("control: landscape_shuffled_across_wells"):
            name = k + " (DERANGED %s)" % [r["across_wells_derangement"] for r in runs]
        L.append("| %s | %s | %s |" % (name, f(np.mean(v)), " | ".join(f(x) for x in v)))
    if cond.startswith("OBS"):
        acc = [r["ROWS"][row]["word_extractor_accuracy"] for r in runs]
        L.append("| word extractor accuracy, whole tuple | %s | %s |"
                 % (f(np.mean([a["whole_tuple"] for a in acc])),
                    " | ".join(f(a["whole_tuple"]) for a in acc)))
        for w in acc[0]["per_word"]:
            L.append("| word extractor accuracy, %s | %s | %s |"
                     % (w, f(np.mean([a["per_word"][w] for a in acc])),
                        " | ".join(f(a["per_word"][w]) for a in acc)))
    return L


def main(out):
    L = ["# w19 maze-t-symmetric — TABLES (generated by scripts/w19_tables.py)", "",
         "⛔ CMAZE-T only. No wave-16 row appears in any table. Every table names its condition.",
         ""]
    # ---------------- the condition table IN FULL
    L += ["## 1. The condition table (in full — wins and losses alike)", "",
          "Primary row = unseen n-way, `exact`. R* = best MATCHED rival over every kind/input "
          "variant AND both budgets (8,000 / 80,000 steps). n_seeds = 3 on every row.", "",
          "| condition | leg | n_seeds | CLU mean | CLU per seed | R* (arm) | R* mean | margin | "
          "max control (bar CLU−0.15) | blind max (bar CLU−0.05) | WORDS floor | B1 | B2 | B3 | B4 | verdict |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for cond in CONDS + DIAGS:
        for leg in ("val", "test"):
            b = bars(out, cond, leg)
            if b is None:
                continue
            p = b["rows"]["nway"]
            verdict = p["label"] + (" (PASS)" if p["PASS_all"] else " (FAIL)")
            if cond in DIAGS:
                verdict = "DIAGNOSTIC ONLY (AMENDMENT 1) — would read " + verdict
            L.append("| %s | %s | %d | %s | %s | %s | %s | %+.3f | %s | %s | %s | %s | %s | %s | %s | %s |"
                     % (cond, leg.upper(), b["n_seeds"], f(p["CLU_mean"]),
                        " / ".join(f(x) for x in p["CLU_per_seed"]), p["R_star"],
                        f(p["R_star_mean"]), p["margin"], f(max(p["controls_mean"].values())),
                        f(p["blind_max"]), f(p["words_floor_mean"]),
                        *["PASS" if p[k] else "FAIL" for k in
                          ("B1_composition", "B2_store_gate", "B3_falsifier", "B4_floor")],
                        verdict))
    L += ["", "B1..B4 = VB1..VB4 on VAL, SB1..SB4 on TEST (PREREG-w19). WORDS-MAIN: B3 on "
          "BLIND-COLOUR only (the CLU IS the learned blind-sequential arm).", ""]
    # ---------------- other rows, labelled
    L += ["## 2. Other rows, labelled (same gate as labels, not bars)", "",
          "| condition | leg | row | n_seeds | CLU | best matched rival (8k/80k) | max control | blind max | label |",
          "|---|---|---|---|---|---|---|---|---|"]
    for cond in CONDS + DIAGS:
        for leg in ("val", "test"):
            b = bars(out, cond, leg)
            if b is None:
                continue
            for row in ("seen", "pair", "value"):
                if row not in b["rows"]:
                    continue
                p = b["rows"][row]
                L.append("| %s | %s | %s | %d | %s | %s (%s) | %s | %s | %s |"
                         % (cond, leg.upper(), row, b["n_seeds"], f(p["CLU_mean"]),
                            f(p["R_star_mean"]), p["R_star"],
                            f(max(p["controls_mean"].values())), f(p["blind_max"]), p["label"]))
    # ---------------- per-step + rollout (limitation, once)
    L += ["", "## 3. Per-step exactness (per condition) and rollout validity (printed ONCE, "
          "as a limitation)", "",
          "| condition | leg | n_seeds | CLU per-step | best rival per-step (arm) | CLU rollout validity | max rival rollout validity |",
          "|---|---|---|---|---|---|---|"]
    for cond in CONDS + DIAGS:
        for leg in ("val", "test"):
            b = bars(out, cond, leg)
            if b is None:
                continue
            ps = b["per_step_exactness"]
            rk = [k for k in ps if k.startswith("rival")]
            best = max(rk, key=lambda k: np.mean(ps[k]))
            L.append("| %s | %s | 3 | %s | %s (%s) | %s | %s |"
                     % (cond, leg.upper(), f(np.mean(ps["CLU"])), f(np.mean(ps[best])), best,
                        f(np.mean(b["rollout"]["CLU"])),
                        f(max(np.mean(b["rollout"][k]) for k in rk))))
    L += ["", "Rollout validity = every step of the full oracle route exact AND goal within "
          "budget, chained on the arm's own generated states. ⚠ Limitation: per-step error "
          "compounds over ~40 steps (0.93^40 ≈ 0.05), so it is ~0 for every learned arm.", ""]
    # ---------------- ledgers
    L += ["## 4. Read-path ledger and matched parameters (per condition)", "",
          "Convention: deployed bytes = 4 × (atom floats + address-book floats), float32; the "
          "float64 sufficient statistic is printed beside, never netted, never matched. In OBS the "
          "extractor floats are ADDED to the matched target (declared).", "",
          "| condition | n_seeds | CLU design | CLU read floats | deployed B (f32) | statistic B (f64) | extractor floats | matched target | rival params (residual %) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for cond in CONDS + DIAGS:
        runs = seeds_json(out, cond, "val")
        if runs is None:
            continue
        r = runs[0]
        mp = "; ".join("%s %d (%+.1f%%, in %d)" % (k, v["params"], v["residual_pct"], v["input_dim"])
                       for k, v in r["matched_parameters"].items())
        L.append("| %s | 3 | %s | %d | %d | %d | %d | %d | %s |"
                 % (cond, r["clu_design"], r["clu_ledger"]["read_floats"],
                    r["clu_ledger"]["deployed_bytes_float32"],
                    r["clu_ledger"]["statistic_bytes_float64"],
                    r["matched_target"]["extractor_floats_added"],
                    r["matched_target"]["target_floats"], mp))
    # ---------------- full arm tables
    L += ["", "## 5. Full arm tables (every arm, every seed)"]
    for cond in CONDS + DIAGS:
        for leg in ("val", "test"):
            runs = seeds_json(out, cond, leg)
            if runs is None:
                continue
            for row in ("nway", "seen", "pair", "value"):
                if all("CLU" in r["ROWS"].get(row, {}) for r in runs):
                    L += arm_table(runs, row, cond, leg)
    # ---------------- deletion
    L += ["", "## 6. Deletion rows (TEST, scored conditions)", "",
          "| condition | seed | mode | rows deleted | store rel. Δ S (bar 1e-5) | atoms max |Δ| | "
          "downdate == fitted-without (n-way rows identical) | CLU n-way after | CLU adapt s | rival retrain-without s (steps) | rival n-way retrain-without / as-trained |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for cond in CONDS:
        runs = seeds_json(out, cond, "test")
        if runs is None:
            continue
        for r in runs:
            D = r["DELETION"]
            for mode in ("value", "conjunction_colour_AND_tinted_floor"):
                b = D.get(mode, {})
                if "store_scoped_exactness" not in b:
                    continue
                s = b["store_scoped_exactness"]
                c = b["composition_on_surviving_colours"].get("nway", {})
                rv = b["rival_composition_on_surviving_colours"].get("nway", {})
                L.append("| %s | %d | %s | %d | %.2e | %.2e | %s | %s | %.2f | %.1f (%d) | %s / %s |"
                         % (cond, r["seed_index"], mode, b["n_rows_deleted"],
                            s["max_relative_delta_S"], s["deployed_atoms_max_abs_delta"],
                            f(c.get("reads_identical_rows_frac")),
                            f(c.get("CLU after deletion (downdate)")),
                            b["clu_adaptation_cost"]["seconds"],
                            b["rival_retrain_without_cost"]["seconds"],
                            b["rival_retrain_without_cost"]["gradient_steps"],
                            f(rv.get("rival retrain-without")), f(rv.get("rival as-trained"))))
    L += ["", "Frozen codec, state encoder and (OBS) word extractor are declared OUTSIDE the "
          "deletable object. CLU post-deletion adaptation is light and data-free (A, Mx, S_k, "
          "t_k, n_k downdated; the same closed form re-solved) — not 'no changes'."]
    open(os.path.join(out, "TABLES.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote TABLES.md (%d lines)" % len(L))


if __name__ == "__main__":
    main(sys.argv[1])
