#!/usr/bin/env python3
"""The four diffs required by tasks/w17/style-paraphrase.md, plus extra verbatim checks.
usage: style_diff_check.py ORIGINAL.tex STYLE.tex > STYLE-DIFF-CHECK.md ; exit 1 if any diff non-empty."""
import sys, re, subprocess
from collections import Counter
from texnum import numbers, comments, src_paths, macro_args, split_comment

A, B = sys.argv[1], sys.argv[2]
ta, tb = open(A).read(), open(B).read()
la, lb = ta.split('\n'), tb.split('\n')
fails = []
out = []
P = out.append

def show_counter_diff(name, ca, cb):
    lost, added = ca - cb, cb - ca
    sa, sb = set(ca), set(cb)
    P('- %s: original %d tokens (%d distinct); style %d tokens (%d distinct).' % (name, sum(ca.values()), len(sa), sum(cb.values()), len(sb)))
    P('- **set diff** original minus style: `%s`; style minus original: `%s`' % (sorted(sa - sb) or '(empty)', sorted(sb - sa) or '(empty)'))
    P('- **multiset diff** (every occurrence) lost: `%s`; added: `%s`' % (dict(lost) or '(empty)', dict(added) or '(empty)'))
    ok = not lost and not added
    if not ok: fails.append(name)
    P('- result: **%s**' % ('EMPTY DIFF' if ok else 'NON-EMPTY - FIX'))
    P('')

P('# STYLE-DIFF-CHECK — `DRAFT-v2.tex` vs `DRAFT-v2-style.tex`')
P('')
P('Generated mechanically by `style_diff_check.py` (w17 spoke/style-paraphrase). Original: `%s` (%d lines). Style: `%s` (%d lines).' % (A, len(la), B, len(lb)))
P('Both files are read whole. "Code" means each line with its LaTeX comment (from the first unescaped `%`) removed.')
P('')
P('## 1. Every number (code only, every digit run, no small-integer or year filter; `\\sci{m}{e}` taken whole)')
P('Tokeniser: the draft-v2 provenance checker\'s regex `(?<![A-Za-z_\\\\{])(\\d[\\d,]*\\.?\\d*)`, trailing `.`/`,` stripped. Section numbers are generated by LaTeX and are not in the source.')
P('')
show_counter_diff('numbers', numbers(la), numbers(lb))

P('## 2. Every `\\PLACEHOLDER{}` (full argument, byte-for-byte, in document order)')
pa, pb = macro_args(ta, 'PLACEHOLDER'), macro_args(tb, 'PLACEHOLDER')
P('- original: %d placeholders; style: %d placeholders.' % (len(pa), len(pb)))
same_order = pa == pb
P('- ordered, byte-identical sequence equal: **%s**' % same_order)
ka = Counter(pa); kb = Counter(pb)
P('- set diff original minus style: `%s`; style minus original: `%s`' % (len(set(ka) - set(kb)), len(set(kb) - set(ka))))
if not same_order: fails.append('placeholders')
P('- result: **%s**' % ('EMPTY DIFF' if same_order else 'NON-EMPTY - FIX'))
P('')
P('Placeholder keys (the row each names), in order:')
P('')
for i, x in enumerate(pa, 1):
    key = re.sub(r'\s+', ' ', x)[:110]
    P('%d. `%s%s`' % (i, key, '…' if len(re.sub(r"\s+", " ", x)) > 110 else ''))
P('')
todo_a, todo_b = macro_args(ta, 'TODO'), macro_args(tb, 'TODO')
P('`\\TODO{}` (same test): original %d, style %d, ordered byte-identical: **%s**.' % (len(todo_a), len(todo_b), todo_a == todo_b))
if todo_a != todo_b: fails.append('todos')
P('')

P('## 3. Every artefact-path comment')
show_counter_diff('artefact paths named in % SRC / % SRCBLOCK comments', src_paths(la), src_paths(lb))
P('Stronger form — every provenance comment string (`% SRC: …`, `% SRCBLOCK: …`, `% ENDSRC`, `% (no result number …)`) compared whole:')
show_counter_diff('provenance comment strings', comments(la), comments(lb))
seq_a = [split_comment(l)[1].strip() for l in la if re.search(r'SRC(BLOCK)?:|ENDSRC', split_comment(l)[1])]
seq_b = [split_comment(l)[1].strip() for l in lb if re.search(r'SRC(BLOCK)?:|ENDSRC', split_comment(l)[1])]
P('- provenance comments in identical document order: **%s** (%d vs %d)' % (seq_a == seq_b, len(seq_a), len(seq_b)))
if seq_a != seq_b: fails.append('comment order')
P('')

P('## 4. Section order')
HEAD = re.compile(r'\\(section|subsection|subsubsection|paragraph)\*?\{')
def heads(text):
    res = []
    code = '\n'.join(split_comment(l)[0] for l in text.split('\n'))
    for m in HEAD.finditer(code):
        k, depth = m.end(), 1
        while depth:
            depth += {'{': 1, '}': -1}.get(code[k], 0); k += 1
        res.append('%s{%s}' % (m.group(1), re.sub(r'\s+', ' ', code[m.end():k-1])))
    return res
def labels(text):
    code = '\n'.join(split_comment(l)[0] for l in text.split('\n'))
    return re.findall(r'\\label\{([^}]*)\}', code)
ha, hb = heads(ta), heads(tb)
P('- headings (section / subsection / subsubsection / paragraph): original %d, style %d; identical sequence: **%s**' % (len(ha), len(hb), ha == hb))
xa, xb = labels(ta), labels(tb)
P('- `\\label{}` sequence (sections, tables, figures): original %d, style %d; identical sequence: **%s**' % (len(xa), len(xb), xa == xb))
if ha != hb: fails.append('headings')
if xa != xb: fails.append('labels')
P('')
P('| # | original | style |')
P('|---|---|---|')
for i in range(max(len(ha), len(hb))):
    a = ha[i] if i < len(ha) else ''
    b = hb[i] if i < len(hb) else ''
    P('| %d | `%s` | `%s` |' % (i + 1, a.replace('|', '\\|'), ('= same' if a == b else b.replace('|', '\\|'))))
P('')

P('## Extra verbatim checks')
def floats(text):
    return re.findall(r'\\begin\{table\}.*?\\end\{table\}|\\figslot\{.*?\}\{fig:[^}]*\}', text, re.S)
fa, fb = floats(ta), floats(tb)
P('- every `table` float and `\\figslot` (with caption) byte-identical and in the same order: **%s** (%d vs %d)' % (fa == fb, len(fa), len(fb)))
if fa != fb: fails.append('floats')
pre_a = ta.split('\\begin{document}')[0].split('\n')[35:]
pre_b = tb.split('\\begin{document}')[0].split('\n')[41:]
P('- preamble from `\\documentclass` to `\\begin{document}` byte-identical: **%s**' % (pre_a == pre_b))
if pre_a != pre_b: fails.append('preamble')
P('- non-ASCII characters in style file: **%d**' % sum(1 for c in tb if ord(c) > 127))
P('')
P('## Verdict')
P('**ALL DIFFS EMPTY.**' if not fails else '**NON-EMPTY: %s**' % ', '.join(fails))
print('\n'.join(out))
sys.exit(1 if fails else 0)
