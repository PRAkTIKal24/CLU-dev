"""n-CLU-REL tables for seeds 0-2.   python scripts/cmazet_tables_relational_first.py <out_dir>"""

import glob
import json
import os
import sys
import numpy as np

LEGDIR = {"val": "val_full", "test": "test"}
CONDS = ("BOTH", "WORDS-FULL")


def f(x):
    return "—" if x is None else "%.3f" % x


def f4(x):
    return "—" if x is None else "%.4f" % x


def runs_of(out, cond, leg):
    ps = [os.path.join(out, LEGDIR[leg], "%s_%s_seed%d.json" % (cond, leg, s)) for s in (0, 1, 2)]
    return [json.load(open(p)) for p in ps] if all((os.path.exists(p) for p in ps)) else None


def lab_of(out, cond, leg):
    p = os.path.join(out, LEGDIR[leg], "LABEL-%s-%s.json" % (cond, leg))
    return json.load(open(p)) if os.path.exists(p) else None


def nice(k, runs):
    if k.startswith("rival: "):
        return k.replace("rival: ", "rival (matched, 8,000 steps): ")
    if k.startswith("rival@10x-steps: "):
        return k.replace("rival@10x-steps: ", "rival (matched, 80,000 steps): ")
    if k.startswith("diagnostic@10x"):
        return k + " (8,000 steps; 10x floats, NOT matched, never a bar)"
    if k.startswith("diagnostic+rel"):
        return k + " (matched floats; input + the CLU's relational columns; never a bar)"
    if k.startswith("control: landscape_shuffled_across_wells"):
        return k + " (DERANGED %s)" % [r["across_wells_derangement"] for r in runs]
    return k


def arm_table(runs, row, cond, leg):
    L = [
        "",
        "#### CMAZE-T · condition **%s** · %s · row `%s` (exact) · CLU = CLU-REL-A10 · n_seeds = %d · rows/seed %s"
        % (cond, leg.upper(), row, len(runs), [r["ROWS"][row]["n"] for r in runs]),
        "",
        "| arm | mean | seed 0 | seed 1 | seed 2 |",
        "|---|---|---|---|---|",
    ]
    keys = [
        k
        for k in runs[0]["ROWS"][row]
        if isinstance(runs[0]["ROWS"][row][k], (int, float))
        and k != "n"
        and (not k.endswith(":coverage"))
    ]
    pref = [
        "CLU",
        "rival: ",
        "rival@10x-steps: ",
        "diagnostic@",
        "diagnostic+rel",
        "control: ",
        "arm: ",
        "floor: ",
        "column: ",
    ]
    order = []
    for p in pref:
        order += [k for k in keys if (k == p if p == "CLU" else k.startswith(p)) and k not in order]
    order += [k for k in keys if k not in order]
    for k in order:
        v = [r["ROWS"][row][k] for r in runs]
        L.append("| %s | %s | %s |" % (nice(k, runs), f(np.mean(v)), " | ".join((f(x) for x in v))))
    return L


def main(out):
    L = [
        "# maze-t-clu-improve — TABLES (generated by scripts/tables.py)",
        "",
        "⛔ CMAZE-T only. CLU = **CLU-REL-A10** (protocol/nclu_rel.json) unless a row says A1. A1 rows are quoted from artefacts.",
        "",
    ]
    L += [
        "## 0. Every VAL candidate (CLU only, closed form, frozen-instrument cache)",
        "",
        "Gate = n-way mean > 0.725 AND every seed ≥ A1 (0.8019 / 0.5689 / 0.8034). Source: `val/sweep_r*.json` (scripts/val_sweep.py). n_seeds = 3 on every row.",
        "",
        "| round | candidate | n_seeds | n-way s0 | s1 | s2 | n-way mean | pair mean | seen mean | value mean | read floats | gate |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    n = 0
    for p in sorted(glob.glob(os.path.join(out, "val", "sweep_r*.json"))):
        rnd = os.path.basename(p)[6:-5]
        for name, r in json.load(open(p)).items():
            if name != "A1-repro":
                n += 1
            gate = (
                "= A1 (instrument check)"
                if name == "A1-repro"
                else "PASS"
                if r["gate_pass"]
                else "FAIL"
            )
            L.append(
                "| %s | %s | 3 | %s | %s | %s | %s | %s | %s | %s | %d | %s |"
                % (
                    rnd,
                    name,
                    *[f4(x) for x in r["nway"]],
                    f4(r["nway_mean"]),
                    f4(r["pair_mean"]),
                    f4(r["seen_mean"]),
                    f4(r["value_mean"]),
                    r["read_floats"],
                    gate,
                )
            )
    L += [
        "",
        "Candidates listed: %d (A1-repro excluded). Frozen: **CLU-REL-A10** (`val/sweep_frozen.json`, identical to r5-atoms10)."
        % n,
        "",
    ]
    L += [
        "## 1. The label table (the earlier study's rule, PROTOCOL §4) — unseen n-way, exact",
        "",
        "R* = best MATCHED rival over every kind AND both budgets. s = std over seeds of (CLU − best matched rival on that seed).",
        "",
        "| condition | leg | n_seeds | CLU mean | CLU per seed | R* (arm) | R* mean | R* per seed | best matched per seed | seeds ahead | s | max control (gate ≤ CLU−0.15) | blind max | WORDS floor | best '+rel' diag (mean) | label |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for cond in CONDS:
        for leg in ("val", "test"):
            b = lab_of(out, cond, leg)
            if b is None:
                if not (cond == "WORDS-FULL" and leg == "test"):
                    L.append(
                        "| %s | %s | — | pending / not run | | | | | | | | | | | | |"
                        % (cond, leg.upper())
                    )
                continue
            p = b["rows"]["nway"]
            L.append(
                "| %s | %s | %d | %s | %s | %s | %s | %s | %s | %d/3 | %s | %s (%s) | %s | %s | %s (%s) | **%s** |"
                % (
                    cond,
                    leg.upper(),
                    b["n_seeds"],
                    f(p["CLU_mean"]),
                    " / ".join((f(x) for x in p["CLU_per_seed"])),
                    p["R_star"],
                    f(p["R_star_mean"]),
                    " / ".join((f(x) for x in p["R_star_per_seed"])),
                    " / ".join((f(x) for x in p["best_matched_rival_per_seed"])),
                    p["seeds_ahead"],
                    f(p["spread_s"]),
                    f(max(p["controls_mean"].values())),
                    "PASS" if p["store_gate"] else "FAIL",
                    f(p["blind_max"]),
                    f(p["words_floor_mean"]),
                    p["diag_rel_best"],
                    f(p["diag_rel_best_mean"]),
                    p["label"],
                )
            )
    L += [
        "",
        "WORDS-FULL TEST: not run by this study (runs 4–6/9 belong to an earlier study; the brief asks for WORDS-FULL on VAL only).",
        "A1 reference (same instrument): BOTH TEST CLU 0.725 (0.800 / 0.566 / 0.808) vs R* lstm-80k 0.626; BOTH VAL CLU 0.725 vs R* 0.617; WORDS-FULL VAL CLU 0.725 vs transformer-8k 0.742.",
        "",
    ]
    L += [
        "## 2. Other rows (same rule, as labels)",
        "",
        "| condition | leg | row | n_seeds | CLU | R* (arm) | best '+rel' diag | max control | blind max | label |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for cond in CONDS:
        for leg in ("val", "test"):
            b = lab_of(out, cond, leg)
            if b is None:
                continue
            for row in ("seen", "pair", "value"):
                if row in b["rows"]:
                    p = b["rows"][row]
                    L.append(
                        "| %s | %s | %s | 3 | %s | %s (%s) | %s | %s | %s | %s |"
                        % (
                            cond,
                            leg.upper(),
                            row,
                            f(p["CLU_mean"]),
                            f(p["R_star_mean"]),
                            p["R_star"],
                            f(p["diag_rel_best_mean"]),
                            f(max(p["controls_mean"].values())),
                            f(p["blind_max"]),
                            p["label"],
                        )
                    )
    L += [
        "",
        "## 3. Per-step exactness and rollout validity (limitation, printed once)",
        "",
        "| condition | leg | n_seeds | CLU per-step | best matched rival per-step (arm) | CLU rollout | max matched rival rollout |",
        "|---|---|---|---|---|---|---|",
    ]
    for cond in CONDS:
        for leg in ("val", "test"):
            b = lab_of(out, cond, leg)
            if b is None:
                continue
            ps = b["per_step_exactness"]
            rk = [k for k in ps if k.startswith("rival")]
            best = max(rk, key=lambda k: np.mean(ps[k]))
            L.append(
                "| %s | %s | 3 | %s | %s (%s) | %s | %s |"
                % (
                    cond,
                    leg.upper(),
                    f(np.mean(ps["CLU"])),
                    f(np.mean(ps[best])),
                    best,
                    f(np.mean(b["rollout"]["CLU"])),
                    f(max((np.mean(b["rollout"][k]) for k in rk))),
                )
            )
    L += [
        "",
        "## 4. Read-path footprint and matched parameters",
        "",
        "Convention: deployed bytes = 4 × (atom floats + address-book floats), float32; the float64 sufficient statistic is printed beside, never netted, never matched.",
        "",
        "| condition | leg | n_seeds | CLU | design width | read floats | deployed B (f32) | statistic B (f64) | matched target | rivals (params, residual %, input dim) | '+rel' diag rivals |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for cond in CONDS:
        for leg in ("val", "test"):
            runs = runs_of(out, cond, leg)
            if runs is None:
                continue
            r = runs[0]
            mp = "; ".join(
                (
                    "%s %d (%+.1f%%, in %d)" % (k, v["params"], v["residual_pct"], v["input_dim"])
                    for k, v in r["matched_parameters"].items()
                )
            )
            rp = "; ".join(
                (
                    "%s %d (%+.1f%%, in %d)" % (k, v["params"], v["residual_pct"], v["input_dim"])
                    for k, v in r.get("rel_diagnostic_parameters", {}).items()
                )
            )
            L.append(
                "| %s | %s | 3 | CLU-REL-A10 | %d | %d | %d | %d | %d | %s | %s |"
                % (
                    cond,
                    leg.upper(),
                    r["clu_footprint"]["design_width"],
                    r["clu_footprint"]["read_floats"],
                    r["clu_footprint"]["deployed_bytes_float32"],
                    r["clu_footprint"]["statistic_bytes_float64"],
                    r["matched_target"]["target_floats"],
                    mp,
                    rp,
                )
            )
    L += [
        "| BOTH (A1) | — | 3 | A1 | 318 | 4,584 | 18,336 | 34,320 | 4,584 | mlp 4,693 / lstm 4,817 / transformer 4,869 (in 954) | — |"
    ]
    L += ["", "## 5. Full arm tables (every arm, every seed)"]
    for cond in CONDS:
        for leg in ("test", "val"):
            runs = runs_of(out, cond, leg)
            if runs is None:
                continue
            for row in ("nway", "seen", "pair", "value"):
                if all(("CLU" in r["ROWS"].get(row, {}) for r in runs)):
                    L += arm_table(runs, row, cond, leg)
    L += [
        "",
        "## 6. Deletion rows (BOTH, TEST — the runs)",
        "",
        "| seed | mode | rows deleted | store rel. Δ S (bar 1e-5) | atoms max abs Δ | downdate == fitted-without (n-way rows identical) | CLU n-way after | CLU adapt s | rival retrain-without s (steps) | rival n-way retrain-without / as-trained |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in runs_of(out, "BOTH", "test") or []:
        for mode in ("value", "conjunction_colour_AND_tinted_floor"):
            b = r["DELETION"].get(mode, {})
            if "store_scoped_exactness" not in b:
                continue
            s = b["store_scoped_exactness"]
            c = b["composition_on_surviving_colours"].get("nway", {})
            rv = b["rival_composition_on_surviving_colours"].get("nway", {})
            L.append(
                "| %d | %s | %d | %.2e | %.2e | %s | %s | %.2f | %.1f (%d) | %s / %s |"
                % (
                    r["seed_index"],
                    mode,
                    b["n_rows_deleted"],
                    s["max_relative_delta_S"],
                    s["deployed_atoms_max_abs_delta"],
                    f(c.get("reads_identical_rows_frac")),
                    f(c.get("CLU after deletion (downdate)")),
                    b["clu_adaptation_cost"]["seconds"],
                    b["rival_retrain_without_cost"]["seconds"],
                    b["rival_retrain_without_cost"]["gradient_steps"],
                    f(rv.get("rival retrain-without")),
                    f(rv.get("rival as-trained")),
                )
            )
    L += [
        "",
        "Frozen codec and state encoder are declared OUTSIDE the deletable object. CLU post-deletion adaptation is light and data-free (A, Mx, S_k, t_k, n_k downdated; the same closed form re-solved) — not 'no changes'.",
    ]
    open(os.path.join(out, "TABLES.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote TABLES.md (%d lines)" % len(L))


if __name__ == "__main__":
    main(sys.argv[1])
