#!/usr/bin/env python3
"""Write CITATIONS-FOR-ZOTERO.md from references.bib: two copyable blocks (arXiv IDs, DOIs)."""
import re, sys
bib, out = sys.argv[1], sys.argv[2]
entries = re.findall(r"@\w+\{([a-z0-9]+),\n(.*?)\n\}", open(bib).read(), re.S)
arx, dois, no_arx, no_doi = [], [], [], []
for key, body in entries:
    a = re.search(r"^  eprint = \{(.+?)\},$", body, re.M)
    d = re.search(r"^  doi = \{(.+?)\},$", body, re.M)
    (arx.append(a.group(1)) if a else no_arx.append(key))
    (dois.append(d.group(1)) if d else no_doi.append(key))
n = len(entries)
md = f"""# CITATIONS-FOR-ZOTERO

Generated by `make_zotero.py` (w17 cite-tagger; re-run by w20 citation-prune) from the pruned `references.bib` ({n} entries, down from 96; see `outputs/w20-citation-prune/CITATION-PRUNE.md`). Paste each block into Zotero's "Add Item by Identifier".

## Block 1: arXiv IDs

```
{chr(10).join(arx)}
```

## Block 2: DOIs

```
{chr(10).join(dois)}
```

**Omitted counts.** Block 1 holds {len(arx)} arXiv IDs. **{len(no_arx)} of {n} entries are omitted from Block 1** because they have no arXiv ID: {", ".join(no_arx)}.
Block 2 holds {len(dois)} DOIs. **{len(no_doi)} of {n} entries are omitted from Block 2** because they have no DOI: {", ".join(no_doi)}.
{len([k for k,_ in entries if k in no_arx and k in no_doi])} entries are in neither block ({", ".join(k for k,_ in entries if k in no_arx and k in no_doi)}); add them to Zotero by hand from `references.bib`.
`lecun2022path` is not in `references.bib`, and so it is in neither block. The citation scout marked it unverified and said not to insert it.
"""
open(out, "w").write(md)
print(n, len(arx), len(dois), len(no_arx), len(no_doi))
